#!/usr/bin/env node
/**
 * Generate TypeScript types from the tracked OpenAPI snapshot.
 *
 * Only the `components` block is kept. The generated `paths` and
 * `operations` blocks are dropped because zm-api's spec ships duplicate
 * `operationId`s — `list_models`, `create_model`, `get_model`,
 * `delete_model`, `update_model` and `update_state` are each declared twice
 * with different shapes — and TypeScript rejects the result with
 * "Duplicate identifier". That is a backend defect (zm-api#32, spec
 * hygiene); dropping the two blocks keeps the half we consume compiling
 * until it is fixed, and this comment is the reminder to restore them.
 *
 * `src/types/api.contract.test-d.ts` checks the hand-written shapes in
 * `src/types/index.ts` against what this produces, at compile time.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const SPEC = 'src/test/openapi/openapi.json';
const OUT = 'src/types/api.generated.ts';

execFileSync('npx', ['openapi-typescript', SPEC, '-o', OUT], { stdio: 'inherit' });

const src = readFileSync(OUT, 'utf8');
// Each top-level block is `export interface <name> {` … `\n}` at column 0.
const block = (name) => new RegExp(`export interface ${name} \\{[\\s\\S]*?\\n\\}\\n`, 'm');
let out = src;
for (const name of ['paths', 'operations', 'webhooks']) {
  out = out.replace(block(name), '');
}
out =
  '// GENERATED by `npm run types:generate` — do not edit.\n' +
  '// Source: src/test/openapi/openapi.json. See scripts/generate-api-types.mjs\n' +
  '// for why `paths`/`operations` are stripped (zm-api#32).\n' +
  out.replace(/^\/\*\*[\s\S]*?\*\/\n/, '');
writeFileSync(OUT, out);

const kept = (out.match(/^export (interface|type) (\w+)/gm) ?? []).map((m) => m.split(' ').pop());
console.log(`types:generate: kept ${kept.join(', ')} (${out.split('\n').length} lines)`);
